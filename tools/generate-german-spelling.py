#!/usr/bin/env python3
"""Generate the pinned German sharp-S lookup table."""

from __future__ import annotations

import argparse
import hashlib
import json
import unicodedata
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = "20095928ca70974fb5d86e44f10181cee16e2831b0d4b1a4ddd12c261aebc5e9"
DEFAULT_SOURCE = ROOT / "build" / "german-spelling-source" / "words"
OUTPUT = ROOT / "src" / "core" / "auto" / "data" / "GermanSharpS.inc"
REQUIRED = {"straße", "straßen", "grüße", "großstadt", "fuß", "weiß"}
EXCLUDED = {"borußia", "großman"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args()

    data = args.source.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"Unexpected source SHA-256: {digest}")

    words = sorted(
        {
            unicodedata.normalize("NFC", line.strip().lower())
            for line in data.decode("utf-8").splitlines()
            if line.strip() and not line.startswith("#")
        },
        key=lambda word: word.encode("utf-8"),
    )
    words = [word for word in words if "ß" in word and word.isalpha()]
    word_set = set(words)
    missing = REQUIRED - word_set
    unexpected = EXCLUDED & word_set
    if missing or unexpected:
        raise SystemExit(f"Input sanity check failed; missing={missing}, unexpected={unexpected}")

    lines = [
        "// Generated by tools/generate-german-spelling.py; do not edit by hand.",
        "// Source: enz/german-wordlist at 1071d87d9535b57b80ec076c699f2578a28ee9dc.",
        f"// Source words SHA-256: {SOURCE_SHA256}.",
        "// Lowercase NFC entries containing ß; presence-only candidate validation.",
        "// See data/NOTICE-german-spelling.md and data/LICENSE-CC0-1.0.txt.",
        "",
        f"constexpr std::array<std::string_view, {len(words)}> kGermanSharpSWords{{{{",
        *(f"    {json.dumps(word, ensure_ascii=False)}," for word in words),
        "}};",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(words)} words; source SHA-256 {digest}")


if __name__ == "__main__":
    main()
