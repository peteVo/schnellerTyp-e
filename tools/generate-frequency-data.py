#!/usr/bin/env python3
"""Generate the checked-in offline frequency tables from wordfreq 3.1.1.

Install build tooling only: python -m pip install --target build/wordfreq-tools wordfreq==3.1.1
Run with Python's module path set to build/wordfreq-tools, or let this script
use that target directory automatically.
"""

from __future__ import annotations

import hashlib
import json
import math
import sys
import unicodedata
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "build" / "wordfreq-tools"
if TOOLS.is_dir():
    sys.path.insert(0, str(TOOLS))

try:
    from wordfreq import available_languages, top_n_list, zipf_frequency
    from importlib.metadata import version
except ImportError as exc:
    raise SystemExit(
        "Install build tooling with: python -m pip install --target "
        "build/wordfreq-tools wordfreq==3.1.1"
    ) from exc


VERSION = "3.1.1"
TABLES = (("English", "en", 30_000), ("German", "de", 40_000), ("Vietnamese", "vi", 15_000))
OUTPUT = ROOT / "src" / "core" / "auto" / "FrequencyData.inc"


def eligible(word: str, lang: str) -> bool:
    word = word.lower()
    if not word.isalpha():
        return False
    if lang == "en":
        return all("a" <= c <= "z" for c in word)
    if lang == "de":
        return all("a" <= c <= "z" or c in "äöüß" for c in word)
    if lang == "vi":
        return all(unicodedata.name(c, "").startswith("LATIN ") for c in word)
    return True


def source_digest(lang: str) -> str:
    data_path = Path(available_languages()[lang])
    return hashlib.sha256(data_path.read_bytes()).hexdigest()


def words_for(lang: str, limit: int) -> list[tuple[str, int]]:
    # Large word lists have far more candidates than the requested filtered caps;
    # Vietnamese has a small list and returns its complete available token set.
    candidates = top_n_list(lang, 250_000)
    frequencies: dict[str, int] = {}
    for candidate in candidates:
        word = candidate.lower()
        if not eligible(word, lang):
            continue
        frequency = math.floor(zipf_frequency(candidate, lang) * 100 + 0.5)
        frequencies[word] = max(frequencies.get(word, 0), frequency)
    ranked = list(frequencies.items())[:limit]
    return sorted(ranked, key=lambda item: item[0].encode("utf-8"))


def main() -> None:
    if version("wordfreq") != VERSION:
        raise SystemExit(f"Expected wordfreq=={VERSION}, found wordfreq=={version('wordfreq')}")

    lines = [
        "// Generated by tools/generate-frequency-data.py; do not edit by hand.",
        "// Source: rspeer/wordfreq 3.1.1, https://github.com/rspeer/wordfreq.",
        "// Data copyright attribution: Robyn Speer. Data licensed CC BY-SA 4.0.",
        "// These are modified, filtered frequency subsets; see data/NOTICE-wordfreq.md",
        "// and data/LICENSE-CC-BY-SA-4.0.txt for attribution and license terms.",
        "// Frequency is round(Zipf frequency * 100). UTF-8 byte order within each table.",
        "",
    ]

    for name, lang, cap in TABLES:
        entries = words_for(lang, cap)
        digest = source_digest(lang)
        lines.append(f"// {name}: {len(entries)} entries; {lang} source SHA-256 {digest}.")
        lines.append(f"constexpr std::array<LexiconEntry, {len(entries)}> k{name}Words{{{{")
        lines.extend(f"    {{{json.dumps(word, ensure_ascii=False)}, {frequency}}}," for word, frequency in entries)
        lines.extend(("}};", ""))
        print(f"{name}: {len(entries)} words (cap {cap}), source SHA-256 {digest}")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
